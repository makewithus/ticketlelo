/**
 * Searches the curated Indian venues catalog using intelligent acronym,
 * prefix, token, and fuzzy scoring.
 *
 * @param {string} rawQuery User typed query (e.g. "akgec", "kiet", "dtu")
 * @param {number} limit Maximum results to return
 * @returns {Array} Scored and sorted venue items
 */
export function searchIndianVenues(rawQuery, limit = 8) {
  if (!rawQuery || typeof rawQuery !== "string") return [];
  const q = rawQuery.trim().toLowerCase();
  if (q.length < 2) return [];

  const qClean = q.replace(/[^a-z0-9\s]/g, " ").replace(/\s+/g, " ").trim();
  const qTokens = qClean.split(" ").filter(Boolean);

  const scored = [];

  for (const venue of INDIAN_VENUES_CATALOG) {
    let score = 0;
    const shortLower = (venue.shortName || "").toLowerCase();
    const nameLower = (venue.name || "").toLowerCase();
    const addressLower = (venue.address || "").toLowerCase();
    const cityLower = (venue.city || "").toLowerCase();

    // 1. Exact acronym match (e.g. "akgec" === "akgec")
    if (shortLower === qClean) {
      score += 1200;
    } else if (venue.aliases.some((alias) => alias.toLowerCase() === qClean)) {
      score += 1100;
    }

    // 2. Prefix acronym match (e.g. user typed "akge" or "akg" when shortName is "akgec")
    if (shortLower.startsWith(qClean) && qClean.length >= 2) {
      score += 900;
    } else if (
      venue.aliases.some((alias) => alias.toLowerCase().startsWith(qClean))
    ) {
      score += 850;
    }

    // 3. Name starts with query
    if (nameLower.startsWith(qClean)) {
      score += 750;
    }

    // 4. Token-based matching: all tokens match name/address/aliases
    const allTokensMatch = qTokens.every(
      (tok) =>
        nameLower.includes(tok) ||
        addressLower.includes(tok) ||
        cityLower.includes(tok) ||
        venue.aliases.some((alias) => alias.toLowerCase().includes(tok))
    );

    if (allTokensMatch) {
      score += 500 + qTokens.length * 50;
    }

    // 5. Partial substring match in name
    if (nameLower.includes(qClean)) {
      score += 300;
    }

    // 6. Address or city contains query
    if (addressLower.includes(qClean) || cityLower.includes(qClean)) {
      score += 150;
    }

    if (score > 0) {
      scored.push({
        id: venue.id,
        name: venue.name,
        address: venue.address,
        city: venue.city,
        state: venue.state,
        pincode: venue.pincode,
        lat: venue.lat,
        lng: venue.lng,
        category: venue.category,
        isVerified: true,
        source: "curated_catalog",
        score,
      });
    }
  }

  // Sort descending by score
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit);
}

/**
 * Extracts a broad, clean venue name and full postal address from raw inputs.
 * Ensures long comma-separated postal addresses are never displayed as the primary venue title.
 */
export function parseVenueDisplay({
  venueName = "",
  address = "",
  city = "",
}) {
  let rawVenue = (venueName || "").trim();
  let rawAddress = (address || "").trim();
  let rawCity = (city || "").trim();

  let broadVenue = rawVenue;
  let fullAddress = rawAddress;

  // If rawVenue is a long, comma-separated address (e.g. "CUSAT, ADM ROAD, Pottachal Nagar, Kalamassery, ...")
  if (rawVenue.includes(",")) {
    const parts = rawVenue.split(",").map((p) => p.trim()).filter(Boolean);
    if (parts.length > 1) {
      // If only 2 short parts (e.g. "CUSAT, Kochi"), keep both as broadVenue
      if (parts.length === 2 && parts[1].length <= 10) {
        broadVenue = `${parts[0]}, ${parts[1]}`;
      } else {
        broadVenue = parts[0];
      }
      if (!fullAddress || fullAddress === rawVenue) {
        fullAddress = rawVenue;
      }
    }
  }

  // If rawAddress is available and has commas while rawVenue was empty
  if (!broadVenue && fullAddress) {
    const parts = fullAddress.split(",").map((p) => p.trim()).filter(Boolean);
    broadVenue = parts[0] || "Venue";
  }

  // If fullAddress is missing, build it from broadVenue and city
  if (!fullAddress) {
    fullAddress = [broadVenue, rawCity].filter(Boolean).join(", ");
  }

  // Extract broad locality/city if not already included in broadVenue
  let broadLocality = rawCity;
  if (!broadLocality && fullAddress.includes(",")) {
    const parts = fullAddress.split(",").map((p) => p.trim()).filter(Boolean);
    for (let i = 1; i < parts.length; i++) {
      const token = parts[i];
      if (!/^\d{6}$/.test(token) && token.toLowerCase() !== "india") {
        broadLocality = token;
        break;
      }
    }
  }

  return {
    broadVenue: broadVenue || "Main Campus Venue",
    broadLocality:
      broadLocality && !broadVenue.toLowerCase().includes(broadLocality.toLowerCase())
        ? broadLocality
        : "",
    fullAddress: fullAddress || broadVenue || "Address details provided upon registration",
  };
}

